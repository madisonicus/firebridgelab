#!/usr/bin/env python3
"""Write docs/examples.md, the examples gallery of the documentation site.

For each bundled example (firebridgelab/examples/*.toml) the page shows its
story (the comment block at the top of the file), the plan file itself, and
the headline output of ``firebridgelab run`` on it (the year-by-year table is
left out). Run from the repository root after the data is fetched:

    python scripts/build_examples_page.py

The numbers depend on the data revision, so rerun this after
``firebridgelab-fetch-data`` picks up a new Shiller file.
tests/test_examples_page.py checks that the page lists every example and
quotes each plan file exactly.
"""

from __future__ import annotations

import contextlib
import io
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from firebridgelab.cli import main as cli_main  # noqa: E402
from firebridgelab.plan import loads  # noqa: E402

EXAMPLES = ROOT / "firebridgelab" / "examples"
OUT = ROOT / "docs" / "examples.md"


def story(text: str) -> str:
    """The leading comment block, as paragraphs, without the first title line."""
    lines = []
    for line in text.splitlines():
        if not line.startswith("#"):
            break
        lines.append(line[1:].strip())
    body = "\n".join(lines[1:]).strip()
    # Keep the "Try:" command as a code block.
    if "Try:" in body:
        prose, _, cmd = body.partition("Try:")
        cmd = " ".join(part.strip().rstrip("\\").strip() for part in cmd.strip().splitlines())
        return f"{prose.strip()}\n\nTry:\n\n```bash\n{cmd}\n```"
    return body


def headline(rel: str) -> str:
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf), contextlib.redirect_stderr(io.StringIO()):
        code = cli_main(["run", rel])
    if code != 0:
        raise SystemExit(f"firebridgelab run {rel} exited {code}")
    out = buf.getvalue()
    return out.split("\nDeterministic, year by year:")[0].rstrip()


def main() -> int:
    parts = [
        "# Examples gallery",
        "",
        "Six fictional households ship with FIRE Bridge Lab as plan files. Each one is a",
        "starting point: copy it with `firebridgelab init --example <name> my-plan.toml`,",
        "edit the numbers, and run it. In the web UI, pick one from the **Examples** menu.",
        "",
        "Below each story is the whole plan file and what `firebridgelab run` prints for it",
        "(the year-by-year table is left out). The numbers depend on the return data and move",
        "slightly when the Shiller file is revised; this page is generated by",
        "`scripts/build_examples_page.py`. [What the numbers mean](faq.md#what-do-the-numbers-mean).",
        "",
        "*All households are fictional. Educational software, not financial advice.*",
    ]
    for path in sorted(EXAMPLES.glob("*.toml")):
        text = path.read_text(encoding="utf-8")
        plan = loads(text, path.name)
        rel = path.relative_to(ROOT).as_posix()
        parts += [
            "",
            f"## {plan.name}",
            "",
            f"`{path.stem}`: {plan.description}",
            "",
            story(text),
            "",
            "??? note \"The plan file\"",
            "",
            "    ```toml",
            *[f"    {line}" if line else "" for line in text.rstrip("\n").splitlines()],
            "    ```",
            "",
            f"`firebridgelab run {rel}`:",
            "",
            "```text",
            headline(rel),
            "```",
        ]
    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
